#!/usr/bin/env python3
"""
Type-checks all project C# against UnityApiStubs.cs, one project per Unity assembly
definition, with the same references as the .asmdef files. Splitting by assembly catches
what a single combined compile cannot: `internal` types used from another assembly, and
references missing from an .asmdef. Engine-free assemblies (noEngineReferences) get no
Unity stubs at all.

Weaker than a Unity compile: the stubs are hand-written. Unity's compile is authoritative.

Usage: python3 Tools/CompileCheck/compile-check.py   (exit code 0 = no errors)
"""
import glob
import json
import os
import subprocess
import sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
GEN = os.path.join(HERE, "gen")
DEFINES = "UNITY_EDITOR;ENABLE_INPUT_SYSTEM"

COMMON = """    <TargetFramework>netstandard2.1</TargetFramework>
    <LangVersion>9.0</LangVersion>
    <Nullable>disable</Nullable>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <NoWarn>CS0649;CS0169;CS0067</NoWarn>"""


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)


def main():
    asmdefs = {}
    for path in glob.glob(os.path.join(ROOT, "Assets", "_Project", "**", "*.asmdef"), recursive=True):
        with open(path) as f:
            data = json.load(f)
        asmdefs[data["name"]] = (os.path.dirname(path), data)

    dirs = {name: d for name, (d, _) in asmdefs.items()}
    projects = []

    write(os.path.join(GEN, "UnityStubs", "UnityStubs.csproj"), f"""<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
{COMMON}
    <DefineConstants>$(DefineConstants);{DEFINES}</DefineConstants>
  </PropertyGroup>
  <ItemGroup><Compile Include="{escape(os.path.join(HERE, 'UnityApiStubs.cs'))}" /></ItemGroup>
</Project>
""")

    for name, (directory, data) in sorted(asmdefs.items()):
        # Files belong to the closest .asmdef above them (Unity's rule).
        files = []
        for cs in glob.glob(os.path.join(directory, "**", "*.cs"), recursive=True):
            owner = max((n for n, d in dirs.items() if cs.startswith(d + os.sep)), key=lambda n: len(dirs[n]))
            if owner == name:
                files.append(cs)

        refs = data.get("references", [])
        items = [f'    <ProjectReference Include="../{r}/{r}.csproj" />' for r in refs if r in asmdefs]
        if not data.get("noEngineReferences", False):
            items.append('    <ProjectReference Include="../UnityStubs/UnityStubs.csproj" />')
        is_test = "UNITY_INCLUDE_TESTS" in data.get("defineConstraints", []) or any("TestRunner" in r for r in refs)
        if is_test:
            items.append('    <PackageReference Include="NUnit" Version="3.14.0" />')
        defines = DEFINES + (";UNITY_INCLUDE_TESTS" if is_test else "")
        compile_items = "\n".join(f'    <Compile Include="{escape(f)}" />' for f in sorted(files))

        write(os.path.join(GEN, name, name + ".csproj"), f"""<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by compile-check.py from {escape(os.path.relpath(directory, ROOT))}. Do not edit. -->
  <PropertyGroup>
{COMMON}
    <AssemblyName>{name}</AssemblyName>
    <DefineConstants>$(DefineConstants);{defines}</DefineConstants>
  </PropertyGroup>
  <ItemGroup>
{compile_items}
  </ItemGroup>
  <ItemGroup>
{chr(10).join(items)}
  </ItemGroup>
</Project>
""")
        projects.append(os.path.join(GEN, name, name + ".csproj"))

    entries = "\n".join(f'    <ProjectReference Include="{escape(p)}" />' for p in projects)
    write(os.path.join(GEN, "All", "All.csproj"), f"""<Project Sdk="Microsoft.NET.Sdk">
  <!-- Builds every generated assembly project. -->
  <PropertyGroup>
    <TargetFramework>netstandard2.1</TargetFramework>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
  </PropertyGroup>
  <ItemGroup>
{entries}
  </ItemGroup>
</Project>
""")

    result = subprocess.run(["dotnet", "build", os.path.join(GEN, "All", "All.csproj"), "-nologo", "-v", "q"],
                            capture_output=True, text=True)
    lines = sorted({l.strip() for l in result.stdout.splitlines() if ": error " in l or ": warning " in l})
    for line in lines:
        print(line.replace(ROOT + os.sep, ""))
    errors = sum(1 for l in lines if ": error " in l)
    warnings = len(lines) - errors
    print(f"{len(asmdefs)} assemblies: {errors} error(s), {warnings} warning(s)")
    return 1 if result.returncode != 0 or errors else 0


if __name__ == "__main__":
    sys.exit(main())
